def main():
    g = load()
    gen_solve_sh(g)
    gen_truth(g)
    rub = gen_rubrics(g)
    compiled_ids = gen_test_output(g, rub)
    payload_hash = gen_provenance_payload(g)

    compiled_weight = sum(i["weight"] for i in rub["items"] if i["mode"] == "compiled")
    total_weight = sum(i["weight"] for i in rub["items"])
    print(json.dumps({
        "compiled_items": compiled_ids,
        "compiled_weight_share": round(compiled_weight / total_weight, 6),
        "compilation_floor": g["compilation_floor"],
        "floor_met": (compiled_weight / total_weight) >= g["compilation_floor"],
        "provenance_payload_sha256": payload_hash,
    }, indent=1))


if __name__ == "__main__":
    main()
